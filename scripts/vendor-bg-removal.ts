// Build step for background removal (D-081): copies onnxruntime-web's CPU
// runtime into public/ and writes the resources.json the library reads, so
// the code it runs in the app's origin comes from this app and not from a
// CDN. Runs before `next build` and `next dev` (package.json); the output is
// generated, so it is git-ignored. Fails, and with it the build, when an
// installed version or a file's hash is not the pinned one.
import { createHash } from "node:crypto"
import { mkdir, readFile, rm, writeFile } from "node:fs/promises"
import path from "node:path"

import { BG_REMOVAL_ASSET_PATH } from "@/lib/images/bg-removal-assets"

import { buildResourceMap, ORT_FILES, PINNED_VERSIONS } from "./bg-removal-vendor"

// pnpm runs package scripts from the package root, so cwd is the project root.
const root = process.cwd()
/** Everything below it is generated by this script and replaced on every run. */
const VENDOR_PREFIX = "/vendor/bg-removal/"
const vendorRoot = path.join(root, "public", "vendor", "bg-removal")
const outDir = path.join(root, "public", ...BG_REMOVAL_ASSET_PATH.split("/").filter(Boolean))

async function installedVersion(name: string): Promise<string> {
  const manifest: unknown = JSON.parse(await readFile(path.join(root, "node_modules", name, "package.json"), "utf8"))
  if (typeof manifest === "object" && manifest !== null && "version" in manifest && typeof manifest.version === "string") {
    return manifest.version
  }
  throw new Error(`${name} has no version in its package.json.`)
}

async function main(): Promise<void> {
  for (const [name, pinned] of Object.entries(PINNED_VERSIONS)) {
    const installed = await installedVersion(name)
    if (installed !== pinned) {
      throw new Error(
        `${name} ${installed} is installed, but PINNED_VERSIONS in src/lib/images/bg-removal-assets.ts pins ${pinned}. ` +
          "Update these together: PINNED_VERSIONS (BG_REMOVAL_ASSET_PATH is built from it, so the files move to a new URL), " +
          "BG_REMOVAL_FILE_BYTES, and ORT_FILES (hashes and sizes) and MODEL_CHUNKS in scripts/bg-removal-vendor.ts.",
      )
    }
  }

  if (!BG_REMOVAL_ASSET_PATH.startsWith(VENDOR_PREFIX)) {
    throw new Error(`BG_REMOVAL_ASSET_PATH must stay below ${VENDOR_PREFIX}, which this script owns.`)
  }
  // Older versions' folders would otherwise be deployed forever.
  await rm(vendorRoot, { recursive: true, force: true })
  await mkdir(outDir, { recursive: true })
  for (const file of ORT_FILES) {
    const bytes = await readFile(path.join(root, "node_modules", "onnxruntime-web", "dist", file.file))
    const sha256 = createHash("sha256").update(bytes).digest("hex")
    if (sha256 !== file.sha256 || bytes.byteLength !== file.size) {
      throw new Error(
        `onnxruntime-web/dist/${file.file} does not match its pin (sha256 ${sha256}, ${bytes.byteLength} bytes). ` +
          "It runs as script in the app's origin, so it is not served.",
      )
    }
    await writeFile(path.join(outDir, file.file), bytes)
  }
  await writeFile(path.join(outDir, "resources.json"), `${JSON.stringify(buildResourceMap(), null, 2)}\n`)
  console.info(`Background removal runtime written to public${BG_REMOVAL_ASSET_PATH}`)
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
